-- Esquema del centro médico (Oracle 21c/23ai).
-- Se conservan los nombres idm_* y los prefijos de columna del proyecto original.
-- Una persona puede ser paciente y empleado a la vez: sus datos viven una sola vez
-- en idm_personas y cada rol guarda su propio estado activo.

CREATE TABLE idm_personas (
    per_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    per_cedula    CHAR(10)      NOT NULL CONSTRAINT uq_personas_cedula UNIQUE,
    per_nombre    VARCHAR2(60)  NOT NULL,
    per_apellido  VARCHAR2(60)  NOT NULL,
    per_direccion VARCHAR2(150),
    per_telefono  VARCHAR2(10)  NOT NULL,
    per_email     VARCHAR2(100)
);

CREATE TABLE idm_pacientes (
    pac_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idm_personas_per_id  NUMBER NOT NULL CONSTRAINT uq_pacientes_persona UNIQUE
                         REFERENCES idm_personas (per_id),
    pac_fecha_nacimiento DATE,
    pac_activo           NUMBER(1) DEFAULT 1 NOT NULL CHECK (pac_activo IN (0, 1))
);

CREATE TABLE idm_empleados (
    emp_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idm_personas_per_id NUMBER NOT NULL CONSTRAINT uq_empleados_persona UNIQUE
                        REFERENCES idm_personas (per_id),
    emp_tipo            VARCHAR2(20) NOT NULL
                        CHECK (emp_tipo IN ('Atencion', 'Medico', 'Administracion')),
    emp_especialidad    VARCHAR2(60),
    emp_activo          NUMBER(1) DEFAULT 1 NOT NULL CHECK (emp_activo IN (0, 1)),
    CONSTRAINT ck_medico_especialidad CHECK (emp_tipo <> 'Medico' OR emp_especialidad IS NOT NULL)
);

CREATE TABLE idm_usuarios (
    usu_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usu_usuario          VARCHAR2(20)  NOT NULL CONSTRAINT uq_usuarios_usuario UNIQUE,
    usu_contrasena       VARCHAR2(200) NOT NULL,  -- hash PBKDF2, nunca la clave
    usu_permiso          VARCHAR2(20)  NOT NULL CHECK (usu_permiso IN ('Recepcion', 'Administrador')),
    usu_activo           NUMBER(1) DEFAULT 1 NOT NULL CHECK (usu_activo IN (0, 1)),
    idm_empleados_emp_id NUMBER NOT NULL CONSTRAINT uq_usuarios_empleado UNIQUE
                         REFERENCES idm_empleados (emp_id)
);

CREATE TABLE idm_servicios (
    ser_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ser_nombre    VARCHAR2(80) NOT NULL CONSTRAINT uq_servicios_nombre UNIQUE,
    ser_precio    NUMBER(10, 2) NOT NULL CHECK (ser_precio > 0),
    ser_grava_iva NUMBER(1) DEFAULT 0 NOT NULL CHECK (ser_grava_iva IN (0, 1)),
    ser_duracion  NUMBER(3) DEFAULT 30 NOT NULL,
    ser_activo    NUMBER(1) DEFAULT 1 NOT NULL CHECK (ser_activo IN (0, 1))
);

CREATE TABLE idm_facturas (
    fac_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fac_numero           CHAR(17) NOT NULL CONSTRAINT uq_facturas_numero UNIQUE,
    fac_fecha            DATE NOT NULL,
    idm_pacientes_pac_id NUMBER NOT NULL REFERENCES idm_pacientes (pac_id),
    fac_subtotal_0       NUMBER(10, 2) NOT NULL,
    fac_subtotal_iva     NUMBER(10, 2) NOT NULL,
    fac_iva              NUMBER(10, 2) NOT NULL,
    fac_total            NUMBER(10, 2) NOT NULL,
    CONSTRAINT ck_factura_total CHECK (fac_total = fac_subtotal_0 + fac_subtotal_iva + fac_iva)
);

CREATE TABLE idm_citas (
    cit_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idm_pacientes_pac_id NUMBER NOT NULL REFERENCES idm_pacientes (pac_id),
    idm_empleados_emp_id NUMBER NOT NULL REFERENCES idm_empleados (emp_id),
    idm_servicios_ser_id NUMBER NOT NULL REFERENCES idm_servicios (ser_id),
    cit_fecha_hora       DATE NOT NULL,
    cit_estado           VARCHAR2(12) DEFAULT 'Reservada' NOT NULL
                         CHECK (cit_estado IN ('Reservada', 'Atendida', 'Cancelada', 'NoAsistio')),
    idm_facturas_fac_id  NUMBER REFERENCES idm_facturas (fac_id)
);

-- Un médico no puede tener dos citas vigentes en el mismo turno. Las canceladas
-- quedan fuera del índice para que el turno se pueda volver a reservar.
CREATE UNIQUE INDEX ux_citas_medico_turno ON idm_citas (
    CASE WHEN cit_estado <> 'Cancelada' THEN idm_empleados_emp_id END,
    CASE WHEN cit_estado <> 'Cancelada' THEN cit_fecha_hora END
);

CREATE INDEX ix_citas_paciente ON idm_citas (idm_pacientes_pac_id);
CREATE INDEX ix_citas_fecha ON idm_citas (cit_fecha_hora);

CREATE TABLE idm_detalles_factura (
    det_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idm_facturas_fac_id  NUMBER NOT NULL REFERENCES idm_facturas (fac_id),
    idm_servicios_ser_id NUMBER NOT NULL REFERENCES idm_servicios (ser_id),
    det_descripcion      VARCHAR2(80) NOT NULL,
    det_cantidad         NUMBER(4) NOT NULL CHECK (det_cantidad > 0),
    det_precio           NUMBER(10, 2) NOT NULL,
    det_grava_iva        NUMBER(1) NOT NULL CHECK (det_grava_iva IN (0, 1)),
    idm_citas_cit_id     NUMBER CONSTRAINT uq_detalles_cita UNIQUE REFERENCES idm_citas (cit_id)
);
